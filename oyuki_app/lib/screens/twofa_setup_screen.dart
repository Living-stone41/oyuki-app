import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:flutter/gestures.dart';
import 'package:qr_flutter/qr_flutter.dart';
import '../theme.dart';
import '../user_session.dart';
import 'twofa_enabled_screen.dart';

class TwoFaSetupScreen extends StatefulWidget {
  const TwoFaSetupScreen({super.key});
  @override
  State<TwoFaSetupScreen> createState() => _TwoFaSetupScreenState();
}

class _TwoFaSetupScreenState extends State<TwoFaSetupScreen> {
  static const setupKey = 'JBSWY3DPEHPK3PXP';
  final _code = List.filled(6, '');
  final _nodes = List.generate(6, (_) => FocusNode());
  final _controllers = List.generate(6, (_) => TextEditingController());

  bool get _complete => _code.every((c) => c.isNotEmpty);

  void _enable() {
    if (!_complete) return;
    Navigator.pushReplacement(
      context,
      MaterialPageRoute(builder: (_) => const TwoFaEnabledScreen()),
    );
  }

  @override
  void dispose() {
    for (var n in _nodes) {
      n.dispose();
    }
    for (var c in _controllers) {
      c.dispose();
    }
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(
        leading: GestureDetector(
          onTap: () => Navigator.pop(context),
          child: const Icon(Icons.arrow_back_ios_new, color: AppColors.green, size: 20),
        ),
        title: const Text('2FA Security'),
      ),
      body: SingleChildScrollView(
        padding: const EdgeInsets.symmetric(horizontal: 20),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            const SizedBox(height: 8),
            const Text.rich(TextSpan(children: [
              TextSpan(
                  text: 'Step 1: ',
                  style: TextStyle(color: AppColors.green, fontWeight: FontWeight.w700)),
              TextSpan(
                  text: 'Use Google authenticator or any compatible authenticator app to scan the QR code',
                  style: TextStyle(color: AppColors.grey)),
            ])),
            const SizedBox(height: 16),
            Center(
              child: Container(
                padding: const EdgeInsets.all(10),
                decoration: BoxDecoration(border: Border.all(color: AppColors.border)),
                child: QrImageView(
                  data:
                      'otpauth://totp/Oyuki:${UserSession.email.isEmpty ? 'account' : UserSession.email}?secret=$setupKey&issuer=Oyuki',
                  size: 180,
                ),
              ),
            ),
            const SizedBox(height: 24),
            const Text('Or enter setup key manually',
                style: TextStyle(color: AppColors.grey, fontSize: 13)),
            const SizedBox(height: 8),
            Row(
              children: [
                Expanded(
                  child: Container(
                    padding: const EdgeInsets.symmetric(horizontal: 14, vertical: 14),
                    decoration: BoxDecoration(
                      border: Border.all(color: AppColors.border),
                      borderRadius: BorderRadius.circular(8),
                    ),
                    child: Text(setupKey,
                        style: const TextStyle(letterSpacing: 1.5, fontSize: 14)),
                  ),
                ),
                const SizedBox(width: 10),
                GestureDetector(
                  onTap: () async {
                    await Clipboard.setData(const ClipboardData(text: setupKey));
                    if (context.mounted) {
                      ScaffoldMessenger.of(context).showSnackBar(
                          const SnackBar(content: Text('Setup key copied')));
                    }
                  },
                  child: Container(
                    width: 48,
                    height: 48,
                    decoration: BoxDecoration(
                        color: AppColors.green,
                        borderRadius: BorderRadius.circular(8)),
                    child: const Icon(Icons.copy_outlined, color: Colors.white, size: 18),
                  ),
                ),
              ],
            ),
            const SizedBox(height: 28),
            const Text.rich(TextSpan(children: [
              TextSpan(
                  text: 'Step 2: ',
                  style: TextStyle(color: AppColors.green, fontWeight: FontWeight.w700)),
              TextSpan(text: 'Enter the 6-digit code generated by authenticator app'),
            ])),
            const SizedBox(height: 16),
            Row(
              mainAxisAlignment: MainAxisAlignment.spaceBetween,
              children: [
                for (var i = 0; i < 6; i++) ...[
                  _otpBox(i),
                  if (i == 2) const Padding(padding: EdgeInsets.symmetric(horizontal: 2), child: Text('—', style: TextStyle(fontSize: 18))),
                ],
              ],
            ),
            const SizedBox(height: 32),
            SizedBox(
              width: double.infinity,
              height: 52,
              child: ElevatedButton(
                onPressed: _enable,
                style: ElevatedButton.styleFrom(
                  backgroundColor: AppColors.green,
                  foregroundColor: Colors.white,
                  shape: RoundedRectangleBorder(
                      borderRadius: BorderRadius.circular(8)),
                ),
                child: const Text('Enable 2FA', style: TextStyle(fontSize: 16)),
              ),
            ),
            const SizedBox(height: 20),
            Center(
              child: Text.rich(TextSpan(
                style: const TextStyle(color: AppColors.grey),
                children: [
                  const TextSpan(text: 'Having issues? '),
                  TextSpan(
                      text: 'Contact support',
                      style: const TextStyle(color: Colors.red),
                      recognizer: TapGestureRecognizer()
                        ..onTap = () {
                          ScaffoldMessenger.of(context).showSnackBar(
                              const SnackBar(content: Text('Opening support chat...')));
                        }),
                ],
              )),
            ),
            const SizedBox(height: 24),
          ],
        ),
      ),
    );
  }

  Widget _otpBox(int i) {
    return SizedBox(
      width: 44,
      height: 56,
      child: TextField(
        controller: _controllers[i],
        focusNode: _nodes[i],
        textAlign: TextAlign.center,
        keyboardType: TextInputType.number,
        maxLength: 1,
        style: const TextStyle(fontSize: 20, fontWeight: FontWeight.w600),
        decoration: InputDecoration(
          counterText: '',
          contentPadding: EdgeInsets.zero,
          border: OutlineInputBorder(
              borderRadius: BorderRadius.circular(8),
              borderSide: const BorderSide(color: AppColors.border)),
          enabledBorder: OutlineInputBorder(
              borderRadius: BorderRadius.circular(8),
              borderSide: const BorderSide(color: AppColors.border)),
          focusedBorder: OutlineInputBorder(
              borderRadius: BorderRadius.circular(8),
              borderSide: const BorderSide(color: AppColors.green)),
        ),
        onChanged: (v) {
          _code[i] = v;
          if (v.isNotEmpty && i < 5) _nodes[i + 1].requestFocus();
          if (v.isEmpty && i > 0) _nodes[i - 1].requestFocus();
          setState(() {});
        },
      ),
    );
  }
}
